// Helper to parse CSV with proper quote escaping and multi-line support
export function parseCsvRows(csvText: string): string[][] {
  const rows: string[][] = [];
  let currentRow: string[] = [];
  let currentCell = '';
  let insideQuotes = false;

  for (let i = 0; i < csvText.length; i++) {
    const char = csvText[i];
    const nextChar = csvText[i + 1];

    if (char === '"') {
      if (insideQuotes && nextChar === '"') {
        currentCell += '"';
        i++; // skip escaped quote
      } else {
        insideQuotes = !insideQuotes;
      }
    } else if (char === ',' && !insideQuotes) {
      currentRow.push(currentCell.trim());
      currentCell = '';
    } else if ((char === '\r' || char === '\n') && !insideQuotes) {
      if (char === '\r' && nextChar === '\n') {
        i++; // skip crlf
      }
      currentRow.push(currentCell.trim());
      if (currentRow.some((cell) => cell.length > 0)) {
        rows.push(currentRow);
      }
      currentRow = [];
      currentCell = '';
    } else {
      currentCell += char;
    }
  }

  if (currentCell.length > 0 || currentRow.length > 0) {
    currentRow.push(currentCell.trim());
    if (currentRow.some((cell) => cell.length > 0)) {
      rows.push(currentRow);
    }
  }

  return rows;
}

// 1. Ingest Grok Question Inventory (JSON)
export function importGrokInventoryJson(jsonString: string): {
  report: ImportReport;
  items: SolutionItem[];
} {
  const report: ImportReport = {
    timestamp: new Date().toISOString(),
    totalParsed: 0,
    importedCount: 0,
    updatedCount: 0,
    skippedCount: 0,
    errors: [],
    warnings: [],
  };

  const items: SolutionItem[] = [];
  let rawData: unknown;

  try {
    rawData = JSON.parse(jsonString);
  } catch (err: unknown) {
    report.errors.push({
      itemIndex: -1,
      message: `Invalid JSON format: ${err instanceof Error ? err.message : String(err)}`,
    });
    return { report, items };
  }

  if (!Array.isArray(rawData)) {
    report.errors.push({
      itemIndex: -1,
      message: 'Root JSON element must be an array of inventory items.',
    });
    return { report, items };
  }

  report.totalParsed = rawData.length;
  const seenIds = new Set<string>();

  rawData.forEach((raw, idx) => {
    const grokItem = raw as Partial<GrokQuestionInventoryItem>;
    const rawId = grokItem.id || `grok-item-${idx + 1}`;

    // Validate ID
    if (!grokItem.id) {
      report.warnings.push({
        itemIndex: idx,
        id: rawId,
        message: 'Missing "id" field in Grok inventory. Autogenerated fallback ID.',
      });
    } else if (seenIds.has(grokItem.id)) {
      report.errors.push({
        itemIndex: idx,
        id: grokItem.id,
        field: 'id',
        message: `Duplicate question ID detected: "${grokItem.id}".`,
      });
      report.skippedCount++;
      return;
    } else {
      seenIds.add(grokItem.id);
    }

    // Required fields check
    if (!grokItem.chapterNumber) {
      report.errors.push({
        itemIndex: idx,
        id: rawId,
        field: 'chapterNumber',
        message: 'Missing "chapterNumber".',
      });
    }
    if (!grokItem.exerciseNumber) {
      report.errors.push({
        itemIndex: idx,
        id: rawId,
        field: 'exerciseNumber',
        message: 'Missing "exerciseNumber".',
      });
    }
    if (!grokItem.questionNumber) {
      report.errors.push({
        itemIndex: idx,
        id: rawId,
        field: 'questionNumber',
        message: 'Missing "questionNumber".',
      });
    }

    // Gujarati text check
    const guQuestion = grokItem.rawQuestionGujarati || '';
    if (!guQuestion) {
      report.errors.push({
        itemIndex: idx,
        id: rawId,
        field: 'rawQuestionGujarati',
        message: 'Missing "rawQuestionGujarati".',
      });
    } else if (!containsGujaratiUnicode(guQuestion)) {
      report.warnings.push({
        itemIndex: idx,
        id: rawId,
        message: 'Gujarati question text does not appear to contain standard Gujarati Unicode characters.',
      });
    }

    // Mathematical formula syntax check
    const formulas = extractLatexFormulas(guQuestion);
    for (const f of formulas) {
      const kCheck = validateKatexFormula(f);
      if (!kCheck.valid) {
        report.warnings.push({
          itemIndex: idx,
          id: rawId,
          message: `KaTeX formula warning in question text: ${kCheck.error}`,
        });
      }
    }

    // Convert inventory item into a draft SolutionItem skeleton
    const solutionSkeleton: SolutionItem = {
      schemaVersion: '2.0',
      id: rawId,
      chapterNumber: (grokItem.chapterNumber || '01').padStart(2, '0'),
      exerciseNumber: grokItem.exerciseNumber || '1.1',
      questionNumber: grokItem.questionNumber || '1',
      topic: {
        en: `Chapter ${grokItem.chapterNumber || '1'} Exercise ${grokItem.exerciseNumber || '1.1'}`,
        gu: `પ્રકરણ ${grokItem.chapterNumber || '1'} સ્વાધ્યાય ${grokItem.exerciseNumber || '1.1'}`,
      },
      originalQuestion: {
        en: grokItem.rawQuestionEnglish || guQuestion,
        gu: guQuestion,
      },
      given: {
        en: ['Given data pending ChatGPT verified solution.'],
        gu: ['આપેલ વિગતો ચકાસાયેલ ઉકેલ પ્રતીક્ષિત છે.'],
      },
      requiredResult: {
        en: 'Pending verified proof/calculation',
        gu: 'સાબિતી અથવા ગણતરી પ્રતીક્ષિત',
      },
      formulaOrTheorem: {
        en: ['Pending theorem'],
        gu: ['પ્રમેય પ્રતીક્ષિત'],
      },
      steps: [
        {
          stepNumber: 1,
          explanation: {
            en: 'Grok extraction recorded. Solution pending verification.',
            gu: 'ગ્રોક પ્રશ્ન નોંધાયેલ છે. ઉકેલ ચકાસણી પ્રતીક્ષિત.',
          },
          math: '\\text{Pending solution}',
        },
      ],
      finalAnswer: {
        en: 'Pending',
        gu: 'પ્રતીક્ષિત',
      },
      verificationStatus: 'missing',
      reviewNotes: grokItem.notes || (grokItem.pageNumber ? `Textbook Page ${grokItem.pageNumber}` : undefined),
    };

    items.push(solutionSkeleton);
    report.importedCount++;
  });

  return { report, items };
}

// 2. Ingest Grok Question Inventory (CSV)
export function importGrokInventoryCsv(csvString: string): {
  report: ImportReport;
  items: SolutionItem[];
} {
  const rows = parseCsvRows(csvString);
  if (rows.length < 2) {
    return {
      report: {
        timestamp: new Date().toISOString(),
        totalParsed: 0,
        importedCount: 0,
        updatedCount: 0,
        skippedCount: 0,
        errors: [{ itemIndex: 0, message: 'CSV has no header or data rows.' }],
        warnings: [],
      },
      items: [],
    };
  }

  // Header mapping
  const headers = rows[0].map((h) => h.toLowerCase().trim());
  const colIndex = {
    id: headers.indexOf('id'),
    chapterNumber: headers.findIndex((h) => h.includes('chapter')),
    exerciseNumber: headers.findIndex((h) => h.includes('exercise')),
    questionNumber: headers.findIndex((h) => h.includes('question')),
    rawQuestionGujarati: headers.findIndex((h) => h.includes('gujarati') || h.includes('question_gu')),
    rawQuestionEnglish: headers.findIndex((h) => h.includes('english') || h.includes('question_en')),
    pageNumber: headers.findIndex((h) => h.includes('page')),
    notes: headers.findIndex((h) => h.includes('note') || h.includes('remarks')),
  };

  const inventoryItems: GrokQuestionInventoryItem[] = [];

  for (let r = 1; r < rows.length; r++) {
    const row = rows[r];
    if (row.length === 0 || (row.length === 1 && !row[0])) continue;

    inventoryItems.push({
      id: colIndex.id >= 0 ? row[colIndex.id] : `csv-item-${r}`,
      chapterNumber: colIndex.chapterNumber >= 0 ? row[colIndex.chapterNumber] : '',
      exerciseNumber: colIndex.exerciseNumber >= 0 ? row[colIndex.exerciseNumber] : '',
      questionNumber: colIndex.questionNumber >= 0 ? row[colIndex.questionNumber] : '',
      rawQuestionGujarati: colIndex.rawQuestionGujarati >= 0 ? row[colIndex.rawQuestionGujarati] : '',
      rawQuestionEnglish: colIndex.rawQuestionEnglish >= 0 ? row[colIndex.rawQuestionEnglish] : undefined,
      pageNumber: colIndex.pageNumber >= 0 ? parseInt(row[colIndex.pageNumber], 10) : undefined,
      notes: colIndex.notes >= 0 ? row[colIndex.notes] : undefined,
    });
  }

  return importGrokInventoryJson(JSON.stringify(inventoryItems));
}

// 3. Ingest ChatGPT Verified Solutions (JSON)
export function importChatGPTVerifiedSolutionsJson(
  jsonString: string,
  existingDatabase: SolutionItem[] = []
): {
  report: ImportReport;
  validSolutions: SolutionItem[];
} {
  const report: ImportReport = {
    timestamp: new Date().toISOString(),
    totalParsed: 0,
    importedCount: 0,
    updatedCount: 0,
    skippedCount: 0,
    errors: [],
    warnings: [],
  };

  const validSolutions: SolutionItem[] = [];
  let rawData: unknown;

  try {
    rawData = JSON.parse(jsonString);
  } catch (err: unknown) {
    report.errors.push({
      itemIndex: -1,
      message: `Invalid JSON format: ${err instanceof Error ? err.message : String(err)}`,
    });
    return { report, validSolutions };
  }

  if (!Array.isArray(rawData)) {
    report.errors.push({
      itemIndex: -1,
      message: 'Root JSON element must be an array of SolutionItem objects.',
    });
    return { report, validSolutions };
  }

  report.totalParsed = rawData.length;
  const existingIdMap = new Map<string, SolutionItem>();
  for (const sol of existingDatabase) {
    existingIdMap.set(sol.id, sol);
  }

  const seenInBatch = new Set<string>();

  rawData.forEach((item, idx) => {
    const rawId = (item as any)?.id || `batch-item-${idx}`;

    if (seenInBatch.has(rawId)) {
      report.errors.push({
        itemIndex: idx,
        id: rawId,
        field: 'id',
        message: `Duplicate ID inside import batch: "${rawId}".`,
      });
      report.skippedCount++;
      return;
    }
    seenInBatch.add(rawId);

    // Schema migration & validation
    const v2Item = migrateSolutionToV2(item);
    const valRes = validateSolutionItem(v2Item, new Set());

    if (!valRes.valid) {
      valRes.errors.forEach((err) => {
        report.errors.push({
          itemIndex: idx,
          id: rawId,
          field: err.field,
          message: err.message,
        });
      });
      report.skippedCount++;
      return;
    }

    if (valRes.warnings.length > 0) {
      valRes.warnings.forEach((warn) => {
        report.warnings.push({
          itemIndex: idx,
          id: rawId,
          message: warn.message,
        });
      });
    }

    // Check if it's an update or new insert
    if (existingIdMap.has(v2Item.id)) {
      report.updatedCount++;
    } else {
      report.importedCount++;
    }

    validSolutions.push(v2Item);
  });

  return { report, validSolutions };
}

// 4. Merge Grok Inventories with Verified Solutions
export function mergeGrokAndChatGPTSolutions(
  grokSkeletons: SolutionItem[],
  verifiedSolutions: SolutionItem[]
): {
  merged: SolutionItem[];
  report: ImportReport;
} {
  const report: ImportReport = {
    timestamp: new Date().toISOString(),
    totalParsed: grokSkeletons.length + verifiedSolutions.length,
    importedCount: 0,
    updatedCount: 0,
    skippedCount: 0,
    errors: [],
    warnings: [],
  };

  const solutionMap = new Map<string, SolutionItem>();

  // Add all Grok skeletons first
  for (const g of grokSkeletons) {
    solutionMap.set(g.id, g);
  }

  // Merge or override with ChatGPT verified solutions
  for (const v of verifiedSolutions) {
    if (solutionMap.has(v.id)) {
      // Retain any page numbers or metadata from Grok if not present in verified
      const existing = solutionMap.get(v.id)!;
      solutionMap.set(v.id, {
        ...existing,
        ...v,
        reviewNotes: v.reviewNotes || existing.reviewNotes,
      });
      report.updatedCount++;
    } else {
      solutionMap.set(v.id, v);
      report.importedCount++;
    }
  }

  return {
    merged: Array.from(solutionMap.values()),
    report,
  };
}
